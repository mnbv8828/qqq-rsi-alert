def _clip_points(condition, points):
    return points if condition else 0


def rank_stocks(ticker, df, benchmark):
    x = df.iloc[-1]
    b = benchmark.iloc[-1]

    score = 0

    # =========================================================
    # 20점: 장기 추세
    # =========================================================

    # 현재가가 200일 이동평균 위
    score += _clip_points(
        x["Close"] > x["MA200"],
        10,
    )

    # 50일 이동평균이 200일 이동평균 위
    score += _clip_points(
        x["MA50"] > x["MA200"],
        10,
    )

    # =========================================================
    # 20점: 모멘텀
    # =========================================================

    # 60일 수익률 양수
    score += _clip_points(
        x["RET60"] > 0,
        10,
    )

    # 120일 수익률 양수
    score += _clip_points(
        x["RET120"] > 0,
        10,
    )

    # =========================================================
    # 20점: QQQ 대비 상대강도
    # =========================================================

    rel20 = (
        x["RET20"]
        - b["RET20"]
    )

    rel60 = (
        x["RET60"]
        - b["RET60"]
    )

    # 최근 20일 QQQ 초과수익
    score += _clip_points(
        rel20 > 0,
        10,
    )

    # 최근 60일 QQQ 초과수익
    score += _clip_points(
        rel60 > 0,
        10,
    )

    # =========================================================
    # 15점: RSI
    #
    # 극단적인 과매수/과매도보다
    # 건강한 중립~상승 구간을 선호
    # =========================================================

    rsi = float(x["RSI"])

    if 45 <= rsi <= 65:
        score += 15

    elif (
        35 <= rsi < 45
        or 65 < rsi <= 70
    ):
        score += 10

    elif 30 <= rsi < 35:
        score += 5

    # RSI < 30
    # RSI > 70
    # → 0점

    # =========================================================
    # 10점: 변동성
    # =========================================================

    vol = float(x["VOL20"])

    if vol < 0.35:
        score += 10

    elif vol < 0.50:
        score += 7

    elif vol < 0.70:
        score += 4

    # VOL20 >= 0.70
    # → 0점

    # =========================================================
    # 15점: 252일 Drawdown
    #
    # 기존 5점 → 15점으로 확대
    # =========================================================

    dd = float(x["DD252"])

    if dd > -0.10:
        score += 15

    elif dd > -0.20:
        score += 9

    # DD252 <= -20%
    # → 0점

    # =========================================================
    # 최종 결과
    # =========================================================

    return {
        "ticker": ticker,
        "stock_score": int(score),
        "rsi": rsi,
        "relative_strength_60d": float(rel60),
        "drawdown_252d": dd,
    }
